/* =====================================================
   05 — ENTER HEART
===================================================== */

function enterHeart() {

    const name =
        nameInput.value
            .trim()
            .toLowerCase();

    const code =
        codeInput.value
            .trim()
            .toLowerCase();


    errorMessage.textContent = "";


    /* ---------------------------------------------
       WRONG NAME
    --------------------------------------------- */

    if (!friends[name]) {

        showError(
            "Sorry... you entered the wrong place of heart. ♡"
        );

        shakeInput();

        return;

    }


    /* ---------------------------------------------
       WRONG PERSONAL CODE
    --------------------------------------------- */

    if (friends[name].code !== code) {

        showError(
            "The name is right... but the key isn't. 🔐"
        );

        shakeInput();

        return;

    }


    /* ---------------------------------------------
       CORRECT FRIEND
    --------------------------------------------- */

    currentFriendKey = name;

    currentFriend = friends[name];


    /* Start music after user interaction */

    music.volume = 0.35;

    music.play().catch(function() {

        console.log("Music could not autoplay.");

    });


    /* Put friend's name */

    document
        .getElementById("friendName")
        .textContent =
        currentFriend.name;


    /* Move to welcome */

    changeScreen(
        "entryScreen",
        "welcomeScreen"
    );

}


